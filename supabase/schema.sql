-- Supabase 建表语句：AI 起名历史（阶段3 使用）
-- 打开 Supabase → SQL Editor，整段粘贴执行一次

-- 1. 建表（字段与实验文档一致，另加 names 便于结构化展示）
create table if not exists public.name_history (
  id                bigint generated by default as identity primary key,
  user_requirement  text not null,                          -- 用户起名需求
  name_result       text not null,                          -- 名字方案（3 组 + 寓意，完整文本）
  model_name        text not null,                          -- 使用的模型，如 kimi-k3.1-pro
  names             jsonb not null default '[]'::jsonb,     -- 结构化方案：[{"name":"…","meaning":"…"}]
  created_at        timestamp with time zone default now()
);

comment on table  public.name_history is 'AI 起名历史记录';
comment on column public.name_history.user_requirement is '用户起名需求';
comment on column public.name_history.name_result is '生成的名字方案（含寓意）';
comment on column public.name_history.model_name is '生成所用模型';
comment on column public.name_history.names is '结构化名字方案';

-- 2. 索引：按时间倒序查最近记录
create index if not exists name_history_created_at_idx
  on public.name_history (created_at desc);

-- 3. 行级安全
--    调试阶段如果要用 anon key 直接读写，可先执行：alter table public.name_history disable row level security;
--    正式上线建议保持 RLS 开启，服务端用 service_role key 写入（自动绕过 RLS）。
alter table public.name_history enable row level security;

